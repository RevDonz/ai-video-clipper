def verdict(case: dict, *, status: int, elapsed_ms: int, code: str | None,
            reason: str | None = None, stored: bytes | None = None, name: str | None = None,
            stage: str) -> dict:
    """One case's result: 2xx = normalised, 4xx = rejected, anything else fails the gate."""
    outcome = "normalised" if 200 <= status < 300 else "rejected" if 400 <= status < 500 else \
        "server_error"
    cap = TIME_CAPS_MS.get(case["kind"], 20_000)
    problems = []
    if outcome == "server_error":
        problems.append(f"status {status}")
    if case["expect"] == "normalise" and outcome != "normalised":
        problems.append("expected a normalised asset")
    if case["expect"] == "reject" and outcome != "rejected":
        problems.append("expected a rejection")
    if elapsed_ms > cap:
        problems.append(f"over the {cap} ms cap")
    if stored is not None and any(marker in stored for marker in MARKERS):
        problems.append("a polyglot payload survived normalisation")
    # Display names never carry a path (identical content keeps its first name, so the exact
    # value is checked by the unit tests of both languages, not here).
    if outcome == "normalised" and name is not None and (
            "/" in name or "\\" in name or name in (".", "..") or len(name) > 80):
        problems.append("a display name kept a path or exceeded 80 characters")
    return {"id": case["id"], "kind": case["kind"], "mime": case["mime"], "bytes": case["bytes"],
            "expect": case["expect"], "stage": stage, "status": status, "outcome": outcome,
            "code": code, "reason": reason, "elapsedMs": elapsed_ms, "capMs": cap,
            "pass": not problems, "problems": problems}


def summarise(results: list[dict], **extra) -> dict:
    counts: dict[str, int] = {}
    for item in results:
        counts[item["outcome"]] = counts.get(item["outcome"], 0) + 1
    by_kind = {}
    for kind in ("logo", "music"):
        times = sorted(item["elapsedMs"] for item in results if item["kind"] == kind)
        if times:
            by_kind[kind] = {"cases": len(times), "maxMs": times[-1]}
    return {
        "schema": "potongin.gate/1",
        "gate": "QG-SEC upload fuzz (plan §9.2, §10.2)",
        "task": "T3.1",
        "threshold": "100% rejected (4xx) or safely normalised (2xx) within the time cap "
                     "(image 20 s, audio 60 s); no 5xx",
        "cases": len(results),
        "rejected": counts.get("rejected", 0),
        "normalised": counts.get("normalised", 0),
        "serverErrors": counts.get("server_error", 0),
        "failed": sum(1 for item in results if not item["pass"]),
        "timesByKind": by_kind,
        "pass": all(item["pass"] for item in results) and bool(results),
        "results": results,
        **extra,
    }


# --- Python level: the Node transport rules, then edit_v2.assets ------------------------------------

_EXIT_STATUS = {0: 201, 4: 404, 9: 409}
_CODE_STATUS = {"asset_type_unsupported": 415, "asset_too_large": 413, "asset_rejected": 422,
                "asset_quota_exceeded": 409}


def run_ingest(corpus_dir: Path, *, jobs_root: Path, job_id: str,
               handle: Callable | None = None, only: Iterable[str] | None = None) -> list[dict]:
    """Every case through the transport rules of ``web/lib/asset-upload.mjs`` (mirrored with
    the shared Python helpers) and ``edit_v2.assets.handle`` in-process."""
    from ai_clipper.edit_v2 import assets

    handle = handle or assets.handle
    corpus_dir = Path(corpus_dir)
    job_dir = Path(jobs_root) / job_id
    (job_dir / "analysis").mkdir(parents=True, exist_ok=True)
    wanted = set(only) if only is not None else None
    results = []
    for case in load_index(corpus_dir)["cases"]:
        if wanted is not None and case["id"] not in wanted:
            continue
        data = (corpus_dir / case["file"]).read_bytes()
        started = time.monotonic()
        transport = _transport(assets, case, data)
        if transport is not None:
            status, code = transport
            results.append(verdict(case, status=status, code=code, stage="transport",
                                   elapsed_ms=round((time.monotonic() - started) * 1000)))
            continue
        incoming = job_dir / "analysis" / "assets" / ".incoming"
        incoming.mkdir(parents=True, exist_ok=True, mode=0o700)
        incoming_id = str(uuid.uuid4())
        fd = os.open(incoming / incoming_id, os.O_WRONLY | os.O_CREAT | os.O_EXCL | os.O_NOFOLLOW,
                     0o600)
        with os.fdopen(fd, "wb") as handle_out:
            handle_out.write(data)
        envelope = {"op": "ingest", "jobId": job_id, "incomingId": incoming_id,
                    "kind": case["kind"], "mime": case["mime"],
                    "name": assets.normalise_name(case["name"]),
                    "idempotencyKey": str(uuid.uuid4())}
        exit_code, payload = handle(json.dumps(envelope).encode(), jobs_root=Path(jobs_root))
        elapsed = round((time.monotonic() - started) * 1000)
        error = payload.get("error") or {}
        status = _EXIT_STATUS.get(exit_code, 500)
        if exit_code == 3:
            status = _CODE_STATUS.get(error.get("code"), 500)
        stored = name = None
        if exit_code == 0:
            asset = payload["asset"]
            suffix = ".png" if asset["kind"] == "logo" else ".m4a"
            stored = (job_dir / "analysis" / "assets" / f"{asset['sha256']}{suffix}").read_bytes()
            name = asset["name"]
        results.append(verdict(case, status=status, code=error.get("code"), reason=error.get("ref"),
                               elapsed_ms=elapsed, stored=stored, name=name, stage="ingest"))
        if (incoming / incoming_id).exists():
            results[-1]["pass"] = False
            results[-1]["problems"].append("the quarantined original survived")
    return results


def _transport(assets, case: dict, data: bytes) -> tuple[int, str] | None:
    """The Node route's own refusals, in its order (web/lib/asset-upload.mjs)."""
    kind, mime = case["kind"], case["mime"]
    if mime not in assets.ALLOWED_TYPES.get(kind, ()):
        return 415, "asset_type_unsupported"
    if len(data) == 0:
        return 400, "invalid_request"
    if len(data) > assets.MAX_UPLOAD_BYTES[kind]:
        return 413, "asset_too_large"
    try:
        assets.normalise_name(case["name"])
    except ValueError:
        return 400, "invalid_request"
    if assets.sniff(data[:64]) != assets.FORMATS[mime]:
        return 415, "asset_type_unsupported"
    return None


# --- HTTP level ----------------------------------------------------------------------------------------


def _login(base: str, username: str, password: str) -> str:
    body = urllib.parse.urlencode({"username": username, "password": password}).encode()
    request = urllib.request.Request(f"{base}/api/auth/login", data=body, method="POST", headers={
        "Content-Type": "application/x-www-form-urlencoded", "Origin": base,
        "Sec-Fetch-Site": "same-origin"})

    class NoRedirect(urllib.request.HTTPRedirectHandler):
        def redirect_request(self, *_args, **_kwargs):
            return None

    opener = urllib.request.build_opener(NoRedirect)
    try:
        response = opener.open(request, timeout=30)
        headers = response.headers
    except urllib.error.HTTPError as error:
        headers = error.headers
    for value in headers.get_all("Set-Cookie") or []:
        name, _, rest = value.partition("=")
        if name.strip() == "potongin_session":
            return rest.split(";", 1)[0]
    raise SystemExit("login failed")


def post_case(base: str, job_id: str, token: str, case: dict, data: bytes) -> tuple[int, dict]:
    headers = {"Origin": base, "Sec-Fetch-Site": "same-origin", "Cookie": f"potongin_session={token}",
               "Content-Type": case["mime"], "X-Asset-Kind": case["kind"],
               "Idempotency-Key": str(uuid.uuid4())}
    if case["name"] is not None:
        headers["X-Asset-Name"] = urllib.parse.quote(case["name"], safe="")
    request = urllib.request.Request(f"{base}/api/jobs/{job_id}/assets", data=data, method="POST",
                                     headers=headers)
    try:
        with urllib.request.urlopen(request, timeout=180) as response:
            return response.status, json.loads(response.read() or b"{}")
    except urllib.error.HTTPError as error:
        try:
            return error.code, json.loads(error.read() or b"{}")
        except ValueError:
            return error.code, {}


def fetch(base: str, path: str, token: str) -> bytes:
    request = urllib.request.Request(f"{base}{path}", headers={
        "Cookie": f"potongin_session={token}"})
    with urllib.request.urlopen(request, timeout=60) as response:
        return response.read()


def run_http(corpus_dir: Path, *, base: str, job_id: str, username: str,
             password: str) -> list[dict]:
    token = _login(base, username, password)
    corpus_dir = Path(corpus_dir)
    results = []
    for case in load_index(corpus_dir)["cases"]:
        data = (corpus_dir / case["file"]).read_bytes()
        started = time.monotonic()
        status, body = post_case(base, job_id, token, case, data)
        elapsed = round((time.monotonic() - started) * 1000)
        stored = None
        if 200 <= status < 300:
            stored = fetch(base, f"/api/jobs/{job_id}/assets/{body['sha256']}", token)
            if hashlib.sha256(stored).hexdigest() != body["sha256"]:
                status = 599  # the served bytes are not the asset: fail the case loudly
        results.append(verdict(case, status=status, code=body.get("code"),
                               reason=body.get("reason"), elapsed_ms=elapsed, stored=stored,
                               name=body.get("name"), stage="http"))
    return results


# --- CLI -------------------------------------------------------------------------------------------


def _toolchain() -> dict:
    ffmpeg = shutil.which("ffmpeg")
    version = "missing"
    if ffmpeg:
        version = subprocess.run([ffmpeg, "-version"], capture_output=True, text=True,
                                 check=False).stdout.split("\n", 1)[0]
    return {"ffmpeg": version, "python": platform.python_version(),
            "machine": platform.machine(), "cpus": os.cpu_count(),
            "load": [round(x, 1) for x in os.getloadavg()]}


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n", 1)[0])
    sub = parser.add_subparsers(dest="command", required=True)
    write = sub.add_parser("write")
    write.add_argument("out_dir", type=Path)
    ingest = sub.add_parser("ingest")
    ingest.add_argument("corpus", type=Path)
    ingest.add_argument("evidence", type=Path)
    ingest.add_argument("--jobs-root", type=Path)
    http = sub.add_parser("http")
    http.add_argument("corpus", type=Path)
    http.add_argument("evidence", type=Path)
    http.add_argument("--base", required=True)
    http.add_argument("--job", required=True)
    http.add_argument("--stack", default="")
    args = parser.parse_args(argv)
    if args.command == "write":
        index = build_corpus(args.out_dir)
        print(json.dumps({"cases": len(index["cases"]), "dir": str(args.out_dir)}))
        return 0
    if args.command == "ingest":
        with tempfile.TemporaryDirectory(prefix="upload-fuzz-jobs-") as tmp:
            root = args.jobs_root or Path(tmp)
            results = run_ingest(args.corpus, jobs_root=root, job_id=str(uuid.uuid4()))
        report = summarise(results, level="python (transport rules + edit_v2.assets.handle)",
                           toolchain=_toolchain())
    else:
        username, password = os.environ.get("APP_USERNAME"), os.environ.get("APP_PASSWORD")
        if not username or not password:
            raise SystemExit("APP_USERNAME and APP_PASSWORD of the test server are required")
        results = run_http(args.corpus, base=args.base.rstrip("/"), job_id=args.job,
                           username=username, password=password)
        report = summarise(results, level="http (POST /api/jobs/:id/assets, next start)",
                           stack=args.stack, toolchain=_toolchain())
    args.evidence.parent.mkdir(parents=True, exist_ok=True)
    args.evidence.write_text(json.dumps(report, indent=1, ensure_ascii=False) + "\n")
    print(json.dumps({key: report[key] for key in ("cases", "rejected", "normalised",
                                                     "serverErrors", "failed", "pass")}))
    return 0 if report["pass"] else 1


if __name__ == "__main__":
    sys.exit(main())
