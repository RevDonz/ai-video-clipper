def _bases(ffmpeg: str, work: Path) -> dict[str, bytes | None]:
    bases: dict[str, bytes | None] = {}
    _ffmpeg(ffmpeg, "-f", "lavfi", "-i", "testsrc2=s=200x150,format=rgba", "-frames:v", "1",
            str(work / "base.png"))
    _ffmpeg(ffmpeg, "-f", "lavfi", "-i", "testsrc2=s=200x150", "-frames:v", "1", "-q:v", "3",
            str(work / "base.jpg"))
    bases["png"] = (work / "base.png").read_bytes()
    bases["jpeg"] = (work / "base.jpg").read_bytes()
    bases["webp"] = None
    if _has_encoder(ffmpeg, "libwebp"):
        _ffmpeg(ffmpeg, "-f", "lavfi", "-i", "testsrc2=s=200x150", "-frames:v", "1", "-c:v",
                "libwebp", str(work / "base.webp"))
        bases["webp"] = (work / "base.webp").read_bytes()
    tone = ["-f", "lavfi", "-i", "sine=f=440:d=3:sample_rate=44100", "-ac", "2"]
    _ffmpeg(ffmpeg, *tone, "-c:a", "pcm_s16le", str(work / "base.wav"))
    _ffmpeg(ffmpeg, *tone, "-c:a", "aac", "-b:a", "128k", str(work / "base.m4a"))
    _ffmpeg(ffmpeg, *tone, "-c:a", "flac", str(work / "base.flac"))
    bases["wav"] = (work / "base.wav").read_bytes()
    bases["m4a"] = (work / "base.m4a").read_bytes()
    bases["flac"] = (work / "base.flac").read_bytes()
    bases["mp3"] = None
    if _has_encoder(ffmpeg, "libmp3lame"):
        _ffmpeg(ffmpeg, *tone, "-c:a", "libmp3lame", "-b:a", "128k", str(work / "base.mp3"))
        bases["mp3"] = (work / "base.mp3").read_bytes()
    bases["ogg"] = None
    if _has_encoder(ffmpeg, "libvorbis"):
        _ffmpeg(ffmpeg, *tone, "-c:a", "libvorbis", str(work / "base.ogg"))
        bases["ogg"] = (work / "base.ogg").read_bytes()
    _ffmpeg(ffmpeg, "-f", "lavfi", "-i", "testsrc2=s=160x120:d=2", "-f", "lavfi", "-i",
            "sine=d=2", "-c:v", "mpeg4", "-c:a", "aac", "-shortest", str(work / "video.mp4"))
    bases["video_mp4"] = (work / "video.mp4").read_bytes()
    return bases


def build_corpus(out_dir: Path, *, ffmpeg: str | None = None) -> dict:
    """Write every case into ``out_dir`` and return the index (also ``out_dir/index.json``)."""
    ffmpeg = ffmpeg or shutil.which("ffmpeg")
    if ffmpeg is None:
        raise SystemExit("ffmpeg is required to build the corpus")
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    rng = random.Random(20260928)
    with tempfile.TemporaryDirectory(prefix="upload-fuzz-") as tmp:
        b = _bases(ffmpeg, Path(tmp))
    png, jpeg, wav, m4a, flac = b["png"], b["jpeg"], b["wav"], b["m4a"], b["flac"]
    assert png and jpeg and wav and m4a and flac
    cases: list[tuple[Case, bytes]] = []

    def add(case_id: str, data: bytes, kind: str, mime: str, expect: str, **extra) -> None:
        cases.append((Case(case_id, f"{case_id}.bin", kind, mime, expect, **extra), data))

    # Images.
    add("png_valid", png, "logo", "image/png", "normalise", name="logo.png")
    add("png_truncated_half", png[: len(png) // 2], "logo", "image/png", "either")
    add("png_truncated_header", png[:30], "logo", "image/png", "reject")
    add("png_bad_crc", png_bad_crc(png), "logo", "image/png", "either")
    add("png_zero_width", png_zero_width(png), "logo", "image/png", "reject")
    add("png_bomb_header", png_bomb_header(), "logo", "image/png", "reject",
        note="decompression-bomb header: 100000x100000")
    add("png_deflate_bomb", png_deflate_bomb(), "logo", "image/png", "either",
        note="64 MiB of zeros from ~65 KB, within the 4096x4096 cap")
    add("png_zip_polyglot", png_zip_polyglot(png), "logo", "image/png", "normalise")
    add("png_apng", png_apng(png), "logo", "image/png", "normalise")
    add("png_text_chunks", png_text_chunks(png), "logo", "image/png", "normalise")
    add("png_random_after_signature", PNG_SIGNATURE + rng.randbytes(4000), "logo", "image/png",
        "reject")
    add("svg_as_png", _svg(), "logo", "image/png", "reject")
    add("svg_as_svg", _svg(), "logo", "image/svg+xml", "reject")
    add("gif_as_png", _gif(), "logo", "image/png", "reject")
    add("gif_as_gif", _gif(), "logo", "image/gif", "reject")
    add("heic_as_png", _heic(), "logo", "image/png", "reject")
    add("heic_as_m4a", _heic(), "music", "audio/mp4", "reject")
    add("pdf_as_png", b"%PDF-1.7\n1 0 obj<<>>endobj\n%%EOF\n", "logo", "image/png", "reject")
    add("jpeg_valid", jpeg, "logo", "image/jpeg", "normalise")
    add("jpeg_truncated", jpeg[: len(jpeg) // 2], "logo", "image/jpeg", "either")
    add("jpeg_garbage", jpeg_garbage(), "logo", "image/jpeg", "reject")
    add("jpeg_huge_sof", jpeg_huge_sof(), "logo", "image/jpeg", "reject")
    add("jpeg_exif_bomb", jpeg_exif_bomb(jpeg), "logo", "image/jpeg", "normalise")
    add("png_as_jpeg", png, "logo", "image/jpeg", "reject")
    if b["webp"]:
        add("webp_valid", b["webp"], "logo", "image/webp", "normalise")
        add("webp_truncated", b["webp"][: len(b["webp"]) // 2], "logo", "image/webp", "either")
    add("webp_huge_vp8x", webp_huge_vp8x(), "logo", "image/webp", "reject")
    add("webp_garbage", b"RIFF\x00\x10\x00\x00WEBPVP8 " + rng.randbytes(4000), "logo",
        "image/webp", "reject")
    add("font_as_png", b"OTTO\x00\x0a\x00\x80" + bytes(200), "logo", "image/png", "reject")
    add("zip_as_webp", _zip(), "logo", "image/webp", "reject")
    add("png_as_music", png, "music", "image/png", "reject")
    # Names (the image itself is valid).
    add("name_traversal", png, "logo", "image/png", "normalise", name="../../../../etc/passwd")
    add("name_windows_path", png, "logo", "image/png", "normalise",
        name="C:\\Windows\\System32\\logo.png")
    add("name_control", png, "logo", "image/png", "reject", name="logo\x00.png")
    add("name_newline", png, "logo", "image/png", "reject", name="logo\r\nX-Injected: 1")
    add("name_too_long", png, "logo", "image/png", "reject", name="x" * 81 + ".png")
    # Transport limits.
    add("empty_logo", b"", "logo", "image/png", "reject")
    add("oversize_logo", png + bytes((10 << 20) + 1 - len(png)), "logo", "image/png", "reject")
    # Music.
    add("wav_valid", wav, "music", "audio/wav", "normalise", name="lagu.wav")
    add("wav_truncated", wav[: len(wav) // 3], "music", "audio/wav", "either")
    add("wav_bad_fmt", wav_bad_fmt(), "music", "audio/wav", "reject")
    add("wav_six_channels", wav_channels(6), "music", "audio/wav", "reject")
    add("m4a_valid", m4a, "music", "audio/mp4", "normalise")
    add("m4a_truncated", m4a[: len(m4a) // 2], "music", "audio/mp4", "either")
    add("mp4_html_polyglot", mp4_html_polyglot(m4a), "music", "audio/mp4", "normalise")
    add("mp4_external_dref", mp4_external_dref(m4a), "music", "audio/mp4", "either")
    add("mp4_with_video", b["video_mp4"], "music", "audio/mp4", "reject")
    add("mkv_external_refs", mkv_external_refs(), "music", "audio/mp4", "reject")
    add("hls_as_mp4", b"#EXTM3U\n#EXT-X-TARGETDURATION:10\n#EXTINF:10,\nfile:///etc/passwd\n"
        b"#EXTINF:10,\nhttp://127.0.0.1:1/x.ts\n#EXT-X-ENDLIST\n", "music", "audio/mp4", "reject")
    add("ffconcat_as_mp3", b"ffconcat version 1.0\nfile '/etc/passwd'\nfile 'http://x/y'\n",
        "music", "audio/mpeg", "reject")
    add("mp3_ten_hours_silent", mp3_ten_hours(lying_xing=False), "music", "audio/mpeg", "reject",
        note="10 h of silent frames, no Xing header")
    add("mp3_ten_hours_lying_xing", mp3_ten_hours(lying_xing=True), "music", "audio/mpeg",
        "reject", note="10 h of frames behind a Xing header that claims 60 s")
    add("mp3_garbage_after_sync", b"\xff\xfb\x90\x64" + rng.randbytes(30_000), "music",
        "audio/mpeg", "either")
    if b["mp3"]:
        add("mp3_valid", b["mp3"], "music", "audio/mpeg", "normalise")
        add("mp3_truncated", b["mp3"][: len(b["mp3"]) // 2], "music", "audio/mpeg", "either")
        add("mp3_huge_id3", mp3_huge_id3(b["mp3"]), "music", "audio/mpeg", "either")
        add("mp3_as_wav", b["mp3"], "music", "audio/wav", "reject")
    if b["ogg"]:
        add("ogg_valid", b["ogg"], "music", "audio/ogg", "normalise")
    add("ogg_garbage", b"OggS\x00\x02" + rng.randbytes(8000), "music", "audio/ogg", "reject")
    add("flac_valid", flac, "music", "audio/flac", "normalise")
