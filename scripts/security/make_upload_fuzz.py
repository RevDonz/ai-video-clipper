def _send(base: str, method: str, path: str, *, headers: dict | None = None,
          body: bytes | None = None, chunked: bool = False) -> tuple[int, dict, bytes]:
    parsed = urllib.parse.urlsplit(base)
    conn = http.client.HTTPConnection(parsed.hostname, parsed.port, timeout=300)
    try:
        conn.putrequest(method, path, skip_accept_encoding=True)
        for name, value in (headers or {}).items():
            conn.putheader(name, value)
        if chunked:
            conn.putheader("Transfer-Encoding", "chunked")
        elif body is not None:
            conn.putheader("Content-Length", str(len(body)))
        conn.endheaders()
        try:
            if chunked and body is not None:
                conn.send(f"{len(body):x}\r\n".encode() + body + b"\r\n0\r\n\r\n")
            elif body is not None:
                view = memoryview(body)
                for start in range(0, len(view), 1 << 20):
                    conn.send(view[start:start + (1 << 20)])
        except (BrokenPipeError, ConnectionResetError):
            pass  # answered early: the answer is read below
        response = conn.getresponse()
        raw = response.read()
        return response.status, {k.lower(): v for k, v in response.getheaders()}, raw
    finally:
        conn.close()


def _code(raw: bytes) -> str | None:
    try:
        value = json.loads(raw or b"{}")
    except ValueError:
        return None
    return value.get("code") if isinstance(value, dict) else None


def tone_wav(seconds: int, rate: int = 48_000) -> bytes:
    """Mono s16 1 kHz at a quarter of full scale; one period repeated (48 samples at 48 kHz)."""
    period = rate // 1000
    cycle = array.array("h", (round(8192 * math.sin(2 * math.pi * n / period))
                              for n in range(period)))
    if sys.byteorder != "little":
        cycle.byteswap()
    data = cycle.tobytes() * (seconds * 1000)
    header = (b"RIFF" + struct.pack("<I", 36 + len(data)) + b"WAVEfmt "
              + struct.pack("<IHHIIHH", 16, 1, 1, rate, rate * 2, 2, 16)
              + b"data" + struct.pack("<I", len(data)))
    return header + data


def run_matrix(base: str, *, job_id: str, username: str, password: str,
               big_seconds: int = 420) -> dict:
    token = _login(base, username, password)
    session = f"potongin_session={token}"
    logo = _png([(b"IHDR", _ihdr(2, 2)), (b"IDAT", zlib.compress(b"\x00" + bytes(8) + b"\x00"
                                                                 + bytes(8))), (b"IEND", b"")])
    upload = f"/api/jobs/{job_id}/assets"

    def headers(**changes) -> dict:
        base_headers = {"Origin": base, "Sec-Fetch-Site": "same-origin", "Cookie": session,
                        "Content-Type": "image/png", "X-Asset-Kind": "logo",
                        "Idempotency-Key": str(uuid.uuid4())}
        base_headers.update({key.replace("_", "-"): value for key, value in changes.items()})
        return {key: value for key, value in base_headers.items() if value is not None}

    def post(path: str, body: bytes | None, head: dict, **options) -> tuple[int, dict, bytes]:
        for _attempt in range(20):  # the 30-per-minute upload rate of the session
            status, answer, raw = _send(base, "POST", path, headers=head, body=body, **options)
            if status != 429:
                return status, answer, raw
            wait = answer.get("retry-after", "2")
            time.sleep(int(wait) if wait.isdigit() else 2)
            head = {**head, "Idempotency-Key": str(uuid.uuid4())}
        return status, answer, raw

    matrix: list[dict] = []

    def check(case: str, expected: int, status: int, raw: bytes, **extra) -> None:
        matrix.append({"case": case, "expected": expected, "status": status, "code": _code(raw),
                       "pass": status == expected and all(extra.values()), **extra})

    for case, expected, path, head, options in [
        ("no session cookie (the route itself, no proxy in front)", 401, upload,
         headers(Cookie=None), {}),
        ("forged session cookie", 401, upload, headers(Cookie="potongin_session=e30.forged"), {}),
        ("no Origin", 403, upload, headers(Origin=None), {}),
        ("foreign Origin", 403, upload, headers(Origin="http://evil.example"), {}),
        ("Sec-Fetch-Site cross-site", 403, upload, headers(Sec_Fetch_Site="cross-site"), {}),
        ("malformed job id", 400, "/api/jobs/not-a-job/assets", headers(), {}),
        ("unknown job", 404, f"/api/jobs/{uuid.uuid4()}/assets", headers(), {}),
        ("chunked body without Content-Length", 411, upload, headers(), {"chunked": True}),
        ("no Idempotency-Key", 400, upload, headers(Idempotency_Key=None), {}),
        ("unknown X-Asset-Kind", 400, upload, headers(X_Asset_Kind="video"), {}),
        ("image/svg+xml for a logo", 415, upload, headers(Content_Type="image/svg+xml"), {}),
        ("SVG bytes declared as PNG", 415, upload, headers(), {"body": _svg()}),
    ]:
        status, _answer, raw = post(path, options.pop("body", logo), head, **options)
        check(case, expected, status, raw)
    status, _answer, raw = post(upload, logo + bytes((10 << 20) + 1 - len(logo)), headers())
    check("a logo one byte over 10 MB", 413, status, raw)

    status, _answer, raw = post(upload, logo, headers(X_Asset_Name=urllib.parse.quote("../Logo Toko.png")))
    check("a valid PNG logo", 201, status, raw)
    asset = json.loads(raw) if status == 201 else {}
    served = f"/api/jobs/{job_id}/assets/{asset.get('sha256', '0' * 64)}"
    status, answer, raw = _send(base, "GET", served)
    check("GET without a session stops at the proxy", 401, status, raw)
    status, answer, raw = _send(base, "GET", served, headers={"Cookie": session})
    check("GET serves the normalised logo with the §9.2 headers", 200, status, raw,
          sha256Matches=hashlib.sha256(raw).hexdigest() == asset.get("sha256"),
          contentType=answer.get("content-type") == "image/png",
          nosniff=answer.get("x-content-type-options") == "nosniff",
          csp=answer.get("content-security-policy") == "default-src 'none'; sandbox",
          corp=answer.get("cross-origin-resource-policy") == "same-origin",
          disposition=answer.get("content-disposition") == 'inline; filename="asset.png"',
          ranges=answer.get("accept-ranges") == "bytes",
          nameIsDisplayOnly=asset.get("name") == "Logo Toko.png")
    status, answer, raw = _send(base, "GET", served, headers={"Cookie": session,
                                                              "Range": "bytes=0-15"})
    check("GET with Range", 206, status, raw, length=len(raw) == 16,
          contentRange=answer.get("content-range", "").startswith("bytes 0-15/"))
    status, answer, raw = _send(base, "GET", f"{served}?part=nope", headers={"Cookie": session})
    check("GET with an unknown part", 400, status, raw)

    wav = tone_wav(big_seconds)
    started = time.monotonic()
    status, _answer, raw = post(upload, wav, headers(Content_Type="audio/wav", X_Asset_Kind="music"))
    elapsed = round((time.monotonic() - started) * 1000)
    music = json.loads(raw) if status == 201 else {}
    whole = abs(music.get("durationMs", 0) - big_seconds * 1000) <= 50
    check(f"a {len(wav) / 1e6:.1f} MB WAV arrives whole (no 10 MB proxy buffer)", 201, status, raw,
          wholeBody=whole)
    matrix[-1].update({"bytes": len(wav), "durationMs": music.get("durationMs"),
                       "elapsedMs": elapsed})
    peaks = f"/api/jobs/{job_id}/assets/{music.get('sha256', '0' * 64)}?part=peaks"
    status, answer, raw = _send(base, "GET", peaks, headers={"Cookie": session})
    check("GET ?part=peaks serves the music waveform", 200, status, raw,
          length=len(raw) == 2 * -(-music.get("durationMs", 0) // 10))
    return {"matrix": matrix, "pass": all(item["pass"] for item in matrix)}


# CLI.


def _toolchain() -> dict:
    ffmpeg = shutil.which("ffmpeg")
    version = "missing"
    if ffmpeg:
        version = subprocess.run([ffmpeg, "-version"], capture_output=True, text=True,
                                 check=False).stdout.split("\n", 1)[0]
    return {"ffmpeg": version, "python": platform.python_version(),
            "machine": platform.machine(), "cpus": os.cpu_count(),
            "load": [round(x, 1) for x in os.getloadavg()]}


def _write(path: Path, report: dict) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(report, indent=1, ensure_ascii=False) + "\n")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n", 1)[0])
    sub = parser.add_subparsers(dest="command", required=True)
    write = sub.add_parser("write")
    write.add_argument("out_dir", type=Path)
    ingest = sub.add_parser("ingest")
    ingest.add_argument("corpus", type=Path)
    ingest.add_argument("evidence", type=Path)
    ingest.add_argument("--jobs-root", type=Path)
    http = sub.add_parser("http")
    http.add_argument("corpus", type=Path)
    http.add_argument("evidence", type=Path)
    http.add_argument("--base", required=True)
    http.add_argument("--job", required=True)
    http.add_argument("--stack", default="")
    matrix = sub.add_parser("matrix")
    matrix.add_argument("evidence", type=Path)
    matrix.add_argument("--base", required=True)
    matrix.add_argument("--job", required=True)
    matrix.add_argument("--environ-log", type=Path)
    matrix.add_argument("--marker", default="planted-secret")
    matrix.add_argument("--stack", default="")
    recorders = sub.add_parser("recorders")
    recorders.add_argument("out_dir", type=Path)
    recorders.add_argument("--log", required=True)
    recorders.add_argument("--interpreter", required=True)
    recorders.add_argument("--python", required=True)
    recorders.add_argument("--ffmpeg", default="/usr/bin/ffmpeg")
    recorders.add_argument("--ffprobe", default="/usr/bin/ffprobe")
    inputs = sub.add_parser("timing-inputs")
    inputs.add_argument("out_dir", type=Path)
    inputs.add_argument("--track-seconds", type=int, default=300)
    timing = sub.add_parser("timing")
    timing.add_argument("inputs", type=Path)
    timing.add_argument("evidence", type=Path)
    timing.add_argument("--python", default=sys.executable)
    timing.add_argument("--pythonpath")
    timing.add_argument("--stack", default="")
    args = parser.parse_args(argv)
    if args.command == "write":
        index = build_corpus(args.out_dir)
        print(json.dumps({"cases": len(index["cases"]), "dir": str(args.out_dir)}))
        return 0
    if args.command == "recorders":
        args.out_dir.mkdir(parents=True, exist_ok=True)
        for tool, real in (("python", args.python), ("ffmpeg", args.ffmpeg),
                           ("ffprobe", args.ffprobe)):
            wrapper = args.out_dir / tool
            wrapper.write_text(recorder_script(real=real, tool=tool, log=args.log,
                                               interpreter=args.interpreter))
            wrapper.chmod(0o755)
        return 0
    if args.command == "timing-inputs":
        found = build_timing_inputs(args.out_dir, track_seconds=args.track_seconds)
        print(json.dumps({"inputs": len(found), "dir": str(args.out_dir)}))
        return 0
    if args.command == "timing":
        listed = json.loads((args.inputs / "timing.json").read_text())
        with tempfile.TemporaryDirectory(prefix="upload-timing-jobs-") as tmp:
            runs = run_timing(args.inputs, listed, jobs_root=Path(tmp), python=args.python,
                              pythonpath=args.pythonpath)
        report = {"schema": "potongin.gate/1", "task": "T3.1",
                  "gate": "ingest p95 (plan §11.3 T3.1): <= 2 s per image, <= 8 s per 5-minute "
                          "track",
                  "method": "python -m ai_clipper.edit_v2.assets ingest, one process per upload "
                            "as the route spawns it (start-up, hashing, probe, normalise, store); "
                            "the stored asset removed after each run so every run writes",
                  **timing_report(runs), "stack": args.stack, "toolchain": _toolchain()}
        _write(args.evidence, report)
        print(json.dumps({key: report[key] for key in ("image", "track5min", "pass")}))
        return 0 if report["pass"] else 1
    if args.command == "matrix":
        username, password = os.environ.get("APP_USERNAME"), os.environ.get("APP_PASSWORD")
        if not username or not password:
            raise SystemExit("APP_USERNAME and APP_PASSWORD of the test server are required")
        report = {"schema": "potongin.gate/1", "task": "T3.1",
                  "gate": "QG-SEC on the real server: the upload route authenticates itself "
                          "without the proxy, a body over 10 MB arrives whole, the §9.2 serving "
                          "headers, and no secret in any child the server spawned (E11)",
                  **run_matrix(args.base.rstrip("/"), job_id=args.job, username=username,
                               password=password)}
        if args.environ_log is not None:
            from ai_clipper.edit_v2 import assets

            allow = {"python": set(child_env_allowlist()),
                     "ffmpeg": set(assets.child_env(Path("/x"))),
                     "ffprobe": set(assets.child_env(Path("/x")))}
            audit = audit_environ(read_environ_log(args.environ_log), allow=allow,
                                  marker=args.marker)
            report["environAudit"] = {**audit, "allowlists": {k: sorted(v) for k, v in
                                                                allow.items()}}
            report["pass"] = report["pass"] and audit["pass"]
        report.update(stack=args.stack, toolchain=_toolchain())
        _write(args.evidence, report)
        print(json.dumps({"checks": len(report["matrix"]), "pass": report["pass"],
                          "environ": report.get("environAudit", {}).get("children")}))
        return 0 if report["pass"] else 1
    if args.command == "ingest":
        with tempfile.TemporaryDirectory(prefix="upload-fuzz-jobs-") as tmp:
            root = args.jobs_root or Path(tmp)
            results = run_ingest(args.corpus, jobs_root=root, job_id=str(uuid.uuid4()))
        report = summarise(results, level="python (transport rules + edit_v2.assets.handle)",
                           toolchain=_toolchain())
    else:
        username, password = os.environ.get("APP_USERNAME"), os.environ.get("APP_PASSWORD")
        if not username or not password:
            raise SystemExit("APP_USERNAME and APP_PASSWORD of the test server are required")
        results = run_http(args.corpus, base=args.base.rstrip("/"), job_id=args.job,
                           username=username, password=password)
        report = summarise(results, level="http (POST /api/jobs/:id/assets, next start)",
                           stack=args.stack, toolchain=_toolchain())
    _write(args.evidence, report)
    print(json.dumps({key: report[key] for key in ("cases", "rejected", "normalised",
                                                     "serverErrors", "failed", "pass")}))
    return 0 if report["pass"] else 1


if __name__ == "__main__":
    sys.exit(main())
