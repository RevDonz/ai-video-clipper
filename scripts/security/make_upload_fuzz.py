def child_env_allowlist(root: Path = ROOT) -> tuple[str, ...]:
    """``CHILD_ENV_ALLOWLIST`` of web/lib/python-cli.mjs: what the route's Python child gets."""
    text = (Path(root) / "web" / "lib" / "python-cli.mjs").read_text(encoding="utf-8")
    block = re.search(r"CHILD_ENV_ALLOWLIST = Object\.freeze\(\[(.*?)\]\)", text, re.DOTALL)
    if block is None:
        raise SystemExit("CHILD_ENV_ALLOWLIST not found in web/lib/python-cli.mjs")
    return tuple(re.findall(r'"([A-Z][A-Z0-9_]*)"', block.group(1)))


def recorder_script(*, real: str, tool: str, log: str, interpreter: str) -> str:
    """A wrapper that appends ``{tool, env}`` (its /proc/self/environ) to ``log`` and execs
    ``real`` with the same arguments."""
    return (f"#!{interpreter}\n"
            "import json, os, sys\n"
            "items = open('/proc/self/environ', 'rb').read().split(b'\\0')\n"
            "env = dict(i.decode('utf-8', 'replace').split('=', 1) for i in items if b'=' in i)\n"
            f"with open({log!r}, 'a', encoding='utf-8') as handle:\n"
            f"    handle.write(json.dumps({{'tool': {tool!r}, 'env': env}}) + '\\n')\n"
            f"os.execv({real!r}, [{real!r}, *sys.argv[1:]])\n")


def audit_environ(records: list[dict], *, allow: dict, marker: str) -> dict:
    """Names outside each tool's allowlist (names only) and values holding ``marker``."""
    outside, planted, by_tool = [], 0, {}
    for record in records:
        tool, env = record["tool"], record["env"]
        by_tool[tool] = by_tool.get(tool, 0) + 1
        for name, value in env.items():
            if name not in allow.get(tool, ()) and {"tool": tool, "name": name} not in outside:
                outside.append({"tool": tool, "name": name})
            planted += marker in value
    return {"children": len(records), "byTool": dict(sorted(by_tool.items())),
            "namesOutsideAllowlist": outside, "plantedValuesFound": planted,
            "pass": bool(records) and not outside and planted == 0}


