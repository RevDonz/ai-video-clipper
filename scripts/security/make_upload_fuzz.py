def run_timing(inputs_dir: Path, inputs: list[dict], *, jobs_root: Path,
               python: str = sys.executable, runs: dict | None = None,
               pythonpath: str | None = None) -> list[dict]:
    """Every input ingested ``runs[class]`` times by ``python -m ai_clipper.edit_v2.assets``
    (start-up, hashing, probe, normalise and store included); the stored asset is removed
    after each run so every run writes."""
    runs = runs or TIMING_RUNS
    job_id = str(uuid.uuid4())
    job_dir = Path(jobs_root) / job_id
    (job_dir / "analysis").mkdir(parents=True)
    env = {name: os.environ[name] for name in ("PATH", "HOME", "LANG", "TZ", "TMPDIR")
           if os.environ.get(name)}
    env["JOBS_ROOT"] = str(jobs_root)
    if pythonpath:
        env["PYTHONPATH"] = pythonpath
    results = []
    for item in inputs:
        data = (Path(inputs_dir) / item["file"]).read_bytes()
        samples, normalised = [], None
        for _ in range(runs[item["class"]]):
            envelope = {"op": "ingest", "jobId": job_id, "incomingId": quarantine(job_dir, data),
                        "kind": item["kind"], "mime": item["mime"], "name": None,
                        "idempotencyKey": str(uuid.uuid4())}
            started = time.monotonic()
            done = subprocess.run([python, "-m", "ai_clipper.edit_v2.assets"],
                                  input=json.dumps(envelope).encode(), capture_output=True,
                                  env=env, timeout=180, check=False)
            samples.append(round((time.monotonic() - started) * 1000))
            try:
                asset = json.loads(done.stdout)["asset"]
            except (ValueError, KeyError):
                raise SystemExit(f"{item['input']}: the ingest failed (exit {done.returncode})"
                                 ) from None
            normalised = {key: asset[key] for key in ("w", "h", "durationMs", "lufsC")}
            for stored in (job_dir / "analysis" / "assets").glob(f"{asset['sha256']}.*"):
                stored.unlink()
        results.append({"input": item["input"], "kind": item["kind"], "class": item["class"],
                        "bytes": len(data), "samplesMs": samples, "normalised": normalised})
    return results


