"""Upload gates of the job asset store (plan §9.2, §10.2, §11.3 T3.1): QG-SEC and ingest timing.

The corpus is generated by this script and never stored in the repository: truncated and
malformed PNG/JPEG/WebP/MP3/M4A/WAV/Ogg/FLAC, PNG+ZIP and MP4+HTML polyglots, an SVG renamed
``.png``, decompression-bomb headers, a 10 h silent MP3 (plain and with a lying Xing header),
Matroska with external references, an HLS playlist renamed ``.mp4``, an FFmpeg concat script,
an MP4 with an external data reference, path-traversal and control-character names, and the
transport limits (empty body, one byte over the cap, a type that does not match the kind).

Gate: **100 %** of the cases are rejected (4xx) or safely normalised (2xx) within their time
cap (image 20 s, audio 60 s), and **no** case produces a 5xx.

Usage (stdlib only; FFmpeg is used to make the valid bases):

    python scripts/security/make_upload_fuzz.py write OUT_DIR
    python scripts/security/make_upload_fuzz.py ingest OUT_DIR EVIDENCE.json
        # every case through the Node transport rules and ``edit_v2.assets`` in-process
    python scripts/security/make_upload_fuzz.py http OUT_DIR EVIDENCE.json --base URL --job ID
        # every case as a real POST /api/jobs/:id/assets; APP_USERNAME / APP_PASSWORD from the
        # environment log in first (a disposable test server, never the owner's app)
    python scripts/security/make_upload_fuzz.py matrix EVIDENCE.json --base URL --job ID \\
        [--environ-log LOG --marker TEXT]
        # authentication without the proxy, CSRF, transport headers, a 40 MB body, the serving
        # headers; with --environ-log, the environment of every child the server spawned (E11)
    python scripts/security/make_upload_fuzz.py recorders DIR --log LOG --interpreter PY \\
        --python REAL_PYTHON
        # wrappers (python, ffmpeg, ffprobe) that log their environment, for the server under test
    python scripts/security/make_upload_fuzz.py timing-inputs DIR
    python scripts/security/make_upload_fuzz.py timing DIR EVIDENCE.json
        # ingest p95: <= 2 s per image, <= 8 s per 5-minute track (one process per upload)
"""

