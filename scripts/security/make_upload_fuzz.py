# --- media helpers -------------------------------------------------------------------------------


def _ffmpeg(ffmpeg: str, *args: str) -> None:
    subprocess.run([ffmpeg, "-nostdin", "-hide_banner", "-loglevel", "error", "-y",
                    "-threads", "2", *args], check=True, timeout=300,
                   stdin=subprocess.DEVNULL)


def _has_encoder(ffmpeg: str, name: str) -> bool:
    out = subprocess.run([ffmpeg, "-hide_banner", "-encoders"], capture_output=True, text=True,
                         check=False).stdout
    return any(line.split()[1:2] == [name] for line in out.splitlines())


def _chunk(kind: bytes, body: bytes) -> bytes:
    return struct.pack(">I", len(body)) + kind + body + struct.pack(
        ">I", zlib.crc32(kind + body) & 0xFFFFFFFF)


def _png_chunks(data: bytes) -> list[tuple[bytes, bytes]]:
    out, position = [], 8
    while position + 12 <= len(data):
        (length,) = struct.unpack(">I", data[position:position + 4])
        out.append((data[position + 4:position + 8], data[position + 8:position + 8 + length]))
        position += 12 + length
    return out


def _png(chunks: Iterable[tuple[bytes, bytes]]) -> bytes:
    return PNG_SIGNATURE + b"".join(_chunk(kind, body) for kind, body in chunks)


def _ihdr(width: int, height: int, depth: int = 8, colour: int = 6) -> bytes:
    return struct.pack(">IIBBBBB", width, height, depth, colour, 0, 0, 0)


def png_bomb_header() -> bytes:
    """IHDR claims 100 000 × 100 000 RGBA (40 GB decoded) over a tiny IDAT."""
    return _png([(b"IHDR", _ihdr(100_000, 100_000)), (b"IDAT", zlib.compress(b"\x00" * 1024)),
                 (b"IEND", b"")])


def png_deflate_bomb() -> bytes:
    """A real 4096 × 4096 RGBA image of zeros: 64 MiB decoded from ~65 KB (within the caps)."""
    row = b"\x00" * (1 + 4096 * 4)
    compressor = zlib.compressobj(9)
    body = b"".join(compressor.compress(row) for _ in range(4096)) + compressor.flush()
    return _png([(b"IHDR", _ihdr(4096, 4096)), (b"IDAT", body), (b"IEND", b"")])


def png_zero_width(base: bytes) -> bytes:
    chunks = _png_chunks(base)
    body = bytearray(chunks[0][1])
    body[0:4] = b"\x00\x00\x00\x00"
    return _png([(b"IHDR", bytes(body)), *chunks[1:]])


def png_bad_crc(base: bytes) -> bytes:
    data = bytearray(base)
    at = data.index(b"IDAT") + 10
    data[at] ^= 0xFF
    return bytes(data)


def png_apng(base: bytes) -> bytes:
    chunks = _png_chunks(base)
    ihdr = chunks[0][1]
    width, height = struct.unpack(">II", ihdr[:8])
    idat = b"".join(body for kind, body in chunks if kind == b"IDAT")

    def fctl(seq: int) -> bytes:
        return struct.pack(">IIIIIHHBB", seq, width, height, 0, 0, 1, 10, 0, 0)

    return _png([(b"IHDR", ihdr), (b"acTL", struct.pack(">II", 2, 0)), (b"fcTL", fctl(0)),
                 (b"IDAT", idat), (b"fcTL", fctl(1)), (b"fdAT", struct.pack(">I", 2) + idat),
                 (b"IEND", b"")])


def png_text_chunks(base: bytes) -> bytes:
    chunks = _png_chunks(base)
    script = b"<html><script>fetch('/api/jobs')</script></html>"
    extra = [(b"tEXt", b"Comment\x00" + script * 200),
             (b"iTXt", b"XML:com.adobe.xmp\x00\x00\x00\x00\x00" + script),
             (b"zTXt", b"Title\x00\x00" + zlib.compress(script * 1000))]
    return _png([chunks[0], *extra, *chunks[1:]])


def png_zip_polyglot(base: bytes) -> bytes:
    buffer = io.BytesIO()
    with zipfile.ZipFile(buffer, "w") as archive:
        archive.writestr("index.html", "<html><script>alert(document.cookie)</script></html>")
    return base + buffer.getvalue()


def jpeg_huge_sof() -> bytes:
    sof = b"\xff\xc0" + struct.pack(">HBHHB", 17, 8, 65000, 65000, 3) + \
        b"\x01\x22\x00\x02\x11\x01\x03\x11\x01"
    return b"\xff\xd8" + sof + b"\xff\xda\x00\x0c\x03\x01\x00\x02\x11\x03\x11\x00\x3f\x00" + \
        bytes(512) + b"\xff\xd9"


def jpeg_exif_bomb(base: bytes) -> bytes:
    """An APP1 whose IFD claims 65 535 entries and points past its end (bounded parsing)."""
    tiff = b"II*\x00" + struct.pack("<I", 8) + struct.pack("<H", 0xFFFF) + \
        struct.pack("<HHII", 0x0112, 3, 0xFFFFFFFF, 0x7FFFFFF0) * 4
    payload = b"Exif\x00\x00" + tiff
    return base[:2] + b"\xff\xe1" + struct.pack(">H", len(payload) + 2) + payload + base[2:]


def jpeg_garbage() -> bytes:
    return b"\xff\xd8\xff\xe0\x00\x10JFIF\x00\x01\x01\x00\x00\x01\x00\x01\x00\x00" + \
        random.Random(7).randbytes(20_000)


def webp_huge_vp8x() -> bytes:
    body = b"\x10\x00\x00\x00" + (16383).to_bytes(3, "little") + (16383).to_bytes(3, "little")
    chunk = b"VP8X" + struct.pack("<I", len(body)) + body
    alph = b"VP8L" + struct.pack("<I", 5) + b"\x2f\xff\x3f\xff\x0f" + b"\x00"
    payload = b"WEBP" + chunk + alph
    return b"RIFF" + struct.pack("<I", len(payload)) + payload


MP3_SILENT_FRAME = b"\xff\xe3\x18\xc4" + bytes(68)  # MPEG-2.5 layer III, 8 kbps, 8 kHz, mono


def mp3_ten_hours(*, lying_xing: bool) -> bytes:
    """10 h of silent 72-byte frames (500 000 × 576 samples at 8 kHz) = 36 MB."""
    frames = 500_000
    first = MP3_SILENT_FRAME
    if lying_xing:  # claims 833 frames (60 s): only the decode cap can catch the real length
        tag = b"Xing" + struct.pack(">II", 1, 833)
        first = first[:13] + tag + first[13 + len(tag):]
    return first + MP3_SILENT_FRAME * (frames - 1)


def mp3_huge_id3(base: bytes) -> bytes:
    size = 20 << 20
    syncsafe = bytes([(size >> 21) & 0x7F, (size >> 14) & 0x7F, (size >> 7) & 0x7F, size & 0x7F])
    return b"ID3\x04\x00\x00" + syncsafe + bytes(size) + base


def _boxes(data: bytes) -> list[tuple[bytes, bytes]]:
    out, position = [], 0
    while position + 8 <= len(data):
        (size,) = struct.unpack(">I", data[position:position + 4])
        kind = data[position + 4:position + 8]
        if size < 8 or position + size > len(data):
            raise ValueError("not a simple box tree")
        out.append((kind, data[position + 8:position + size]))
        position += size
    return out


def _box(kind: bytes, body: bytes) -> bytes:
    return struct.pack(">I", len(body) + 8) + kind + body


_CONTAINERS = {b"moov", b"trak", b"mdia", b"minf", b"dinf"}


def _patch_dref(data: bytes) -> bytes:
    out = []
    for kind, body in _boxes(data):
        if kind == b"dref":
            location = b"file:///etc/passwd\x00"
            entry = _box(b"url ", b"\x00\x00\x00\x00" + location)  # flags 0: external data
            body = body[:4] + struct.pack(">I", 1) + entry
        elif kind in _CONTAINERS:
            body = _patch_dref(body)
        out.append(_box(kind, body))
    return b"".join(out)


def mp4_external_dref(base: bytes) -> bytes:
    """The 'url ' data reference of the audio track made external (``-enable_drefs 0``)."""
    return _patch_dref(base)


def mp4_html_polyglot(base: bytes) -> bytes:
    html = b"<!DOCTYPE html><html><body><script>alert(document.cookie)</script></body></html>"
    return base + _box(b"free", html * 10)


def mkv_external_refs() -> bytes:
    ebml = bytes.fromhex("1a45dfa3") + b"\xa3" + bytes.fromhex("4282") + b"\x88matroska" + \
        bytes.fromhex("42870104") + bytes.fromhex("42850102")
    # Segment → Info → SegmentFilename/NextFilename pointing at other files (linked segments).
    info = bytes.fromhex("3b8375") + b"\x8b/etc/passwd" + bytes.fromhex("3e83bb") + b"\x87../x.mkv"
    segment = bytes.fromhex("18538067") + b"\x01\x00\x00\x00\x00\x00\x00\x40" + \
        bytes.fromhex("1549a966") + bytes([0x80 | len(info)]) + info
    return ebml + segment + bytes(64)


def wav_bad_fmt() -> bytes:
    fmt = struct.pack("<HHIIHH", 1, 0, 0, 0, 0, 16)
    data = bytes(4000)
    body = b"WAVE" + b"fmt " + struct.pack("<I", len(fmt)) + fmt + b"data" + \
        struct.pack("<I", len(data)) + data
    return b"RIFF" + struct.pack("<I", len(body)) + body


def wav_channels(channels: int, seconds: float = 1.0, rate: int = 8000) -> bytes:
    frames = int(seconds * rate)
    fmt = struct.pack("<HHIIHH", 1, channels, rate, rate * channels * 2, channels * 2, 16)
    data = bytes(frames * channels * 2)
    body = b"WAVE" + b"fmt " + struct.pack("<I", len(fmt)) + fmt + b"data" + \
        struct.pack("<I", len(data)) + data
    return b"RIFF" + struct.pack("<I", len(body)) + body


def _svg() -> bytes:
    return (b"<?xml version=\"1.0\"?><svg xmlns=\"http://www.w3.org/2000/svg\" width=\"64\" "
            b"height=\"64\" onload=\"alert(1)\"><image href=\"file:///etc/passwd\"/></svg>")


def _gif() -> bytes:
    return (b"GIF89a\x01\x00\x01\x00\x80\x00\x00\x00\x00\x00\xff\xff\xff!\xf9\x04\x01\x00\x00\x00"
            b"\x00,\x00\x00\x00\x00\x01\x00\x01\x00\x00\x02\x02D\x01\x00;")


def _heic() -> bytes:
    return _box(b"ftyp", b"heic\x00\x00\x00\x00mif1heic") + _box(b"meta", bytes(64))


def _zip() -> bytes:
    buffer = io.BytesIO()
    with zipfile.ZipFile(buffer, "w") as archive:
        archive.writestr("a.txt", "x" * 100)
    return buffer.getvalue()


